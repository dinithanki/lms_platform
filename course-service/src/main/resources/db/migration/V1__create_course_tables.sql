CREATE TABLE courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    description TEXT,
    owner_id BIGINT,
    title VARCHAR(255) NOT NULL,
    CONSTRAINT courses_pkey PRIMARY KEY (id)
);

CREATE TABLE modules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    description TEXT,
    resource_url VARCHAR(255),
    sequence_order INTEGER NOT NULL,
    title VARCHAR(255) NOT NULL,
    video_url VARCHAR(255) NOT NULL,
    course_id BIGINT NOT NULL,
    CONSTRAINT modules_pkey PRIMARY KEY (id),
    CONSTRAINT modules_course_id_fkey FOREIGN KEY (course_id) REFERENCES courses (id)
);

CREATE TABLE enrollments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    course_id BIGINT NOT NULL,
    enrolled_at TIMESTAMP NOT NULL,
    student_id BIGINT NOT NULL,
    CONSTRAINT enrollments_pkey PRIMARY KEY (id),
    CONSTRAINT enrollments_student_id_course_id_key UNIQUE (student_id, course_id)
);

CREATE TABLE module_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    completed BOOLEAN NOT NULL,
    completed_at TIMESTAMP,
    module_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL,
    CONSTRAINT module_progress_pkey PRIMARY KEY (id),
    CONSTRAINT module_progress_student_id_module_id_key UNIQUE (student_id, module_id)
);

CREATE TABLE quiz_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    attempts INTEGER NOT NULL,
    course_id BIGINT NOT NULL,
    score DOUBLE PRECISION NOT NULL,
    student_id BIGINT NOT NULL,
    CONSTRAINT quiz_results_pkey PRIMARY KEY (id),
    CONSTRAINT quiz_results_student_id_course_id_key UNIQUE (student_id, course_id)
);

CREATE TABLE certificates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    certificate_id VARCHAR(255) NOT NULL,
    course_id BIGINT NOT NULL,
    issued_date TIMESTAMP NOT NULL,
    score DOUBLE PRECISION NOT NULL,
    student_id BIGINT NOT NULL,
    CONSTRAINT certificates_pkey PRIMARY KEY (id),
    CONSTRAINT certificates_certificate_id_key UNIQUE (certificate_id),
    CONSTRAINT certificates_student_id_course_id_key UNIQUE (student_id, course_id)
);
